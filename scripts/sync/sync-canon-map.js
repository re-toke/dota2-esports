// scripts/sync-canon-map.js
// G4 — 消除云函数与小程序「双源漂移」：从唯一手工维护来源 utils/curation.js 的
// CURATED_EVENTS 生成「赛事名规范映射」curation-shared.js（CommonJS 模块），并镜像到
// 云函数目录，保证两侧共用同一份精确归一映射。
//
// ⚠️ 产物必须是 .js 模块（module.exports = {...}），不能用 .json：
//    微信小程序 require() 不支持直接加载 .json —— 会被补成
//    'curation-shared.json.js' 然后报 "module is not defined"。
//
// 归一规则与 consensus.normName 对齐（仅 ASCII 联赛名，等价于 [^a-z0-9]）：
//   小写 + 去除非字母数字，得到归一键；canonical 与所有 aliases 都写入同一 map。
//
// 用法：node scripts/sync-canon-map.js
// 退出码 0 = 成功且两侧一致；非 0 = 失败（CI 中据此拦截）。

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const MINI_JS = path.join(ROOT, 'utils', 'curation-shared.js');

// 复用 curation 的归一口径（与 consensus.normName 一致，ASCII 名等价）
// §8.3 多语言支持（2026-07-29）：与 consensus.normName 同步，保留西里尔字母
function normKey(s) {
  return String(s == null ? '' : s).toLowerCase().replace(/[^a-z0-9一-鿿а-яё]/g, '');
}

function buildMap() {
  const curation = require(path.join(ROOT, 'utils', 'curation.js'));
  const events = curation.CURATED_EVENTS || [];
  const map = {};
  // 2026-07-27：新增 leagueIdMap（leagueId -> canonical），供云函数推送等场景
  // 在 leagueId 已知时精确 pin，跳过模糊别名漂移。
  const leagueIdMap = {};
  let count = 0;
  events.forEach((ev) => {
    if (!ev || !ev.canonical) return;
    const canonKey = normKey(ev.canonical);
    if (canonKey) { map[canonKey] = ev.canonical; count++; }
    (ev.aliases || []).forEach((a) => {
      const k = normKey(a);
      if (k) { map[k] = ev.canonical; count++; }
    });
    if (ev.leagueId != null) leagueIdMap[ev.leagueId] = ev.canonical;
  });
  return { map, leagueIdMap, count };
}

function serialize(map, leagueIdMap, count, dataVersion) {
  const payload = {
    version: 3,
    generatedAt: new Date().toISOString(),
    source: 'utils/curation.js#CURATED_EVENTS',
    eventCount: count,
    map,
    // 2026-07-27：leagueId pin 映射，供云函数推送文案等场景精确命中。
    leagueIdMap,
    // 2026-07-27：数据版本戳。每次 sync 重生即更新，作为客户端 / 云函数缓存 key 的前缀，
    // 实现"代码部署即缓存失效"的语义（详见 sync-canon-map.js 头部注释）。
    dataVersion: dataVersion || '0'
  };
  const header =
    '// AUTO-GENERATED by scripts/sync-canon-map.js — DO NOT EDIT BY HAND.\n' +
    '// Single source of truth: utils/curation.js (CURATED_EVENTS)\n' +
    "// Consumed via require('./curation-shared') by both Mini Program and\n" +
    '// cloudfunctions/aggregation (CommonJS module, NOT .json — WeChat require\n' +
    '// cannot load .json directly).\n';
  return header + 'module.exports = ' + JSON.stringify(payload, null, 2) + ';\n';
}

function main() {
  const { map, leagueIdMap, count } = buildMap();
  if (count === 0) {
    console.error('[sync-canon-map] 致命：生成的映射为空，请检查 utils/curation.js');
    process.exit(1);
  }
  // 2026-07-27：数据版本戳。每次运行 sync 重新生成时更新，作为客户端 / 云函数缓存 key 的一部分。
  // 缓存失效原理：sync 后 dataVersion 改变 → 旧缓存（key 包含旧版本）永远不会被命中 → 相当于"代码部署后强制刷新"。
  // 解决"云函数部署后数据未正确更新"的根因：之前 cloud DB 缓存 + 客户端 wx.storage 缓存都跨部署持久化，
  // 现通过版本戳使旧 key 自动失效。
  const dataVersion = String(Date.now());

  // §6.2 差异检测（2026-07-29）：对比新旧 map，输出新增/删除/变更条目
  // 便于本地调试时确认 curation 变更是否生效，避免"改了 curation 但没 sync"的困惑
  let diffSummary = '';
  try {
    const oldModule = require(MINI_JS);
    const oldMap = (oldModule && oldModule.map) || {};
    const added = [], removed = [], changed = [];
    Object.keys(map).forEach((k) => {
      if (!(k in oldMap)) added.push(k + ' -> ' + map[k]);
      else if (oldMap[k] !== map[k]) changed.push(k + ': ' + oldMap[k] + ' -> ' + map[k]);
    });
    Object.keys(oldMap).forEach((k) => {
      if (!(k in map)) removed.push(k + ' (was: ' + oldMap[k] + ')');
    });
    if (added.length || removed.length || changed.length) {
      diffSummary = '\n  新增 ' + added.length + ' 条，删除 ' + removed.length + ' 条，变更 ' + changed.length + ' 条';
      if (added.length) console.log('[sync-canon-map] + 新增映射:');
      added.slice(0, 10).forEach((s) => console.log('    + ' + s));
      if (added.length > 10) console.log('    ... 等共 ' + added.length + ' 条');
      if (removed.length) console.log('[sync-canon-map] - 删除映射:')
      removed.slice(0, 10).forEach((s) => console.log('    - ' + s));
      if (removed.length > 10) console.log('    ... 等共 ' + removed.length + ' 条');
      if (changed.length) console.log('[sync-canon-map] ~ 变更映射:')
      changed.slice(0, 10).forEach((s) => console.log('    ~ ' + s));
      if (changed.length > 10) console.log('    ... 等共 ' + changed.length + ' 条');
    } else {
      diffSummary = '\n  映射无变化（产物保持不变，时间戳不更新）';
    }
  } catch (e) {
    // 首次生成无旧文件，跳过 diff
    diffSummary = '\n  (首次生成，无旧版本可对比)';
  }

  const text = serialize(map, leagueIdMap, count, dataVersion);

  // ★ 2026-09-18 幂等化（修复 CI 第 4 步"永久失败"）：
  //   generatedAt / dataVersion 每次 sync 都取当前时间戳 → 产物必然与上次不同 →
  //   CI 里「跑 sync:canon 后 git diff --quiet」的检查**必然失败**，
  //   **与产物是否最新无关**（这是 CI 从未变绿的第三个阻塞点，属设计缺陷）。
  //   现改为：若除这两个时间戳外的内容与现有产物完全一致，则复用现有文本
  //   （即保留旧时间戳），使产物逐字节稳定 —— 真正做到"内容变了才产生 diff"。
  // 比对采用「解析后的内容指纹」而非字符串替换 —— 后者易受格式/空白/行尾符差异干扰。
  const _sig = function (p) {
    return JSON.stringify([p.version, p.source, p.eventCount, p.map, p.leagueIdMap]);
  };
  let outText = text;
  try {
    if (fs.existsSync(MINI_JS)) {
      delete require.cache[require.resolve(MINI_JS)];
      const oldPayload = require(MINI_JS);
      const newPayload = {
        version: 3,
        source: 'utils/curation.js#CURATED_EVENTS',
        eventCount: count,
        map: map,
        leagueIdMap: leagueIdMap
      };
      if (_sig(oldPayload) === _sig(newPayload)) {
        outText = fs.readFileSync(MINI_JS, 'utf8');   // 复用原文件原文（含旧时间戳）
        console.log('[sync-canon-map] 映射内容无变化 → 复用现有产物（时间戳不变，不产生 diff）');
      }
    }
  } catch (e) { /* 读取/解析失败则按新文本写入 */ }

  // 写入小程序侧
  fs.mkdirSync(path.dirname(MINI_JS), { recursive: true });
  fs.writeFileSync(MINI_JS, outText, 'utf8');

  // ★ 2026-09-22（微信云开发退役）：原「镜像到 cloudfunctions/aggregation/curation-shared.js」
  //   及其两侧一致性断言**已移除** —— 云函数已退役，不再需要云侧副本。
  //   G4 的核心不变量（内容由 utils/curation.js 单一来源生成）改由 CI 校验一文件
  //   （见 .github/workflows/ci.yml：跑完脚本后 git diff --quiet -- utils/curation-shared.js）。

  // EPL 覆盖自检（2026-07-27 修复后语义变更；2026-08-31 P0 判届升级）：
  // 现保留窄别名 'epl masters i' / 'epl masters ii' + leagueId 精确 pin（19944）。
  // 19944 被 Masters I/II 复用：leagueIdMap 采用「最新届覆盖」语义（last-write wins，
  // 条目按时间顺序排列 → II 在后），供云函数推送文案取当届名；客户端多届判届
  // 由 curation.js 的 leagueIdWindow（pinLookup）负责，与本静态 map 无关。
  // 1) canonical 自映射：I / II 均必须映射回自身；
  // 2) leagueId pin：19944 必须命中最新届（当前 = EPL Masters II）；
  // 3) 回归防护：过宽别名 'epl2026' / 'eplmasters2026' 不得映射到任何 EPL 届。
  const eplSelfOk = map['eplmastersi'] === 'EPL Masters I' && map['eplmastersii'] === 'EPL Masters II';
  const eplPinOk = leagueIdMap[19944] === 'EPL Masters II';
  const eplOverBroad = ['epl2026', 'eplmasters2026'].filter((k) => map[k] === 'EPL Masters I' || map[k] === 'EPL Masters II');
  if (!eplSelfOk) {
    console.error('[sync-canon-map] 致命：EPL canonical 自映射缺失（eplmastersi / eplmastersii）');
    process.exit(1);
  }
  if (!eplPinOk) {
    console.error('[sync-canon-map] 致命：EPL leagueId pin 缺失（19944 -> 最新届 EPL Masters II）');
    process.exit(1);
  }
  if (eplOverBroad.length) {
    console.error('[sync-canon-map] 致命：EPL 过宽别名回归（不应映射到任何 EPL 届）: ' + eplOverBroad.join(', '));
    process.exit(1);
  }

  console.log('[sync-canon-map] OK · 事件覆盖 ' + count + ' 条 · 两侧 curation-shared.js 内容一致 · EPL pin+映射完整' + diffSummary);
}

main();
